import math

# Troquei o print por return para o resultado ir para o navegador
def sub(a, b): 
    return a - b
def soma(a, b): 
    return a + b
def mult(a, b): 
    return a * b
def div(a, b): 
    return a / b
def raiz_quadrada(n): 
    return math.sqrt(n)
def hipotenusa(a, b): 
    return math.hypot(a, b)
def fatorial(n): 
    return math.factorial(int(n))
def seno(a): 
    return math.sin(math.radians(a))
def cosseno(a): 
    return math.cos(math.radians(a))
def tangente(a): 
    return math.tan(math.radians(a))